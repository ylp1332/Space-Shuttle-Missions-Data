"""Tests for the mission extraction pipeline.

Fast unit tests cover the pure helpers; data tests read
data/missions.csv (generated by scripts/extract_missions.py -- the
session fixture regenerates it if missing).
"""

import os
import subprocess
import sys

import re as _re

import pandas as pd
import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

from extract_missions import (  # noqa: E402
    GMT_RE, TIME4_RE, find_duration, normalize, year2)
import shuttle_pdf as sp  # noqa: E402


# ---------------- pure helpers ----------------

def test_normalize_squeezes_digits_colons_slashes():
    assert normalize("1 33 / 19A") == "133/19A"
    assert normalize("302 : 19 : 33 : 98Z") == "302:19:33:98Z"
    assert normalize("46. 95") == "46.95"
    assert normalize("( P )") == "(P )"


def test_year2():
    assert year2(83) == 1983
    assert year2(11) == 2011


def test_gmt_re_matches_all_variants():
    for s in ("102:12:00:03.9Z", "324:19:55:46.95Z", "34:12:59:59:998Z",
              "189:15:29:04Z", "20:09:35:36.2Z"):
        assert _re.search(GMT_RE, s), s
    m = _re.search(GMT_RE, "34:12:59:59:998Z")
    assert m.group(1) == "34" and m.group(4) == "59"


def test_time4_re_rejects_gmt_stamps():
    assert TIME4_RE.search("duration 10:07:47:24 MET")
    assert TIME4_RE.search("20:09:35:36 .2Z") is None   # GMT with frac
    assert TIME4_RE.search("261:11:37:55Z") is None      # GMT day stamp





def test_find_duration_prefers_valid_stamp():
    text = "FLT DURATION,\nWINDS\nEDW 22\n261:11:37:55Z\n...\nFLT DURATION:\n10:20:28:56\n248:28"
    m = find_duration(text)
    assert m is not None
    assert int(m.group(1)) == 10


def test_rejoin_merges_wide_tracking():
    assert sp.rejoin("S T S - 1 3 5") == "STS-135"
    assert sp.rejoin("FLT # 1 3 5") == "FLT # 135"


def test_base_designation():
    assert sp.base_designation("STS-88/2A") == "88"
    assert sp.base_designation("STS 41-C") == "41-C"
    assert sp.base_designation("STS-117/13A4") == "117"


# ---------------- data tests ----------------

@pytest.fixture(scope="session")
def missions_df():
    csv_path = os.path.join(ROOT, "data", "missions.csv")
    if not os.path.exists(csv_path):
        subprocess.run([sys.executable, "-I",
                        os.path.join(ROOT, "scripts", "extract_missions.py")],
                       cwd=ROOT, check=True)
    return pd.read_csv(csv_path)


@pytest.fixture(scope="session")
def flown(missions_df):
    return missions_df[missions_df.cancelled == 0].copy()


def row(flown, design):
    r = flown[flown.designation == design]
    assert len(r) == 1, f"{design!r}: expected 1 row, got {len(r)}"
    return r.iloc[0]


def test_135_flights_plus_one_cancelled(missions_df, flown):
    assert len(missions_df) == 136
    assert len(flown) == 135
    seqs = set(flown.flight_seq.dropna().astype(int))
    assert seqs == set(range(1, 136))
    cancelled = missions_df[missions_df.cancelled == 1]
    assert cancelled.designation.tolist() == ["STS 51-E"]


def test_sts1_reference_values(flown):
    r = row(flown, "STS-1")
    assert r.flight_seq == 1
    assert r.orbiter == "Columbia"
    assert r.launch_date == "1981-04-12"
    assert str(r.launch_dt_utc) == "1981-04-12 12:00:03"
    assert r.landing_date == "1981-04-14"
    assert r.landing_site.startswith("EDW")
    assert r.duration.startswith("2d 06:20")
    assert abs(r.duration_hours - 54.348) < 0.01
    assert r.crew_size == 2
    assert abs(r.inclination_deg - 40.3) < 0.05


def test_sts135_reference_values(flown):
    r = row(flown, "STS-135")
    assert r.flight_seq == 135
    assert r.orbiter == "Atlantis"
    assert r.launch_date == "2011-07-08"
    assert r.landing_site.startswith("KSC")
    assert r.crew_size == 4
    assert abs(r.inclination_deg - 51.6) < 0.05
    assert 306 < r.duration_hours < 308      # 12d 18h


def test_challenger_51L_has_no_landing(flown):
    r = row(flown, "STS 51-L")
    assert r.launch_date == "1986-01-28"
    assert pd.isna(r.landing_date)
    assert r.duration_hours < 0.1            # 73 s ascent


def test_columbia_107_duration(flown):
    r = row(flown, "STS-107")
    assert r.launch_date == "2003-01-16"
    assert 380 < r.duration_hours < 383      # 15d 21:36 derived


def test_sts9_derived_duration(flown):
    r = row(flown, "STS-9")
    assert r.duration_source == "derived"
    assert abs(r.duration_hours - 247.8) < 0.5


def test_key_field_completeness(flown):
    for col in ("launch_date", "launch_dt_utc", "duration_hours",
                "crew_size", "orbiter", "inclination_deg"):
        missing = flown[flown[col].isna()].designation.tolist()
        assert missing == [], f"{col} missing: {missing}"
    # only the two accidents lack a landing site/date
    assert flown[flown.landing_site.isna()].designation.tolist() == ["STS 51-L"]


def test_orbiter_counts_match_history(flown):
    counts = flown.orbiter.value_counts().to_dict()
    assert counts == {"Discovery": 39, "Atlantis": 33,
                      "Endeavour": 25, "Columbia": 28, "Challenger": 10}


def test_launch_dates_monotonic(flown):
    dates = flown.sort_values("flight_seq").launch_date.reset_index(drop=True)
    assert dates.is_monotonic_increasing


def test_all_inclinations_plausible(flown):
    inc = flown.inclination_deg.dropna()
    assert ((inc >= 28.0) & (inc <= 62.5)).all()


def test_crew_sizes_plausible(flown):
    cs = flown.crew_size.dropna()
    assert ((cs >= 2) & (cs <= 8)).all()
